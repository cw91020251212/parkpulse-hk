import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = (path) => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const map = await read('src/components/MapView.tsx');
const app = await read('src/App.tsx');
const info = await read('src/components/PositionInfo.tsx');
const css = await read('src/components/PositionInfo.css');
assert.match(map, /<Popup className="position-info-popup"[^>]*closeButton><PositionInfo point=\{position\} language=\{language\} gps=\{showCurrentLocation\} areaName=\{positionLabel\} \/><\/Popup><\/Marker>/);
assert.match(map, /keyboard title=\{text\(language, 'pinOpenInfo'\)\}/);
assert.match(map, /<LongPressPicker onPick=/);
assert.match(map, /navigation\.open\('popup'/);
assert.match(app, /positionLabel=\{displayedAreaName\}/);
assert.match(info, /<Official3DLink point=\{point\}/);
assert.match(info, /point\.lat\.toFixed\(6\)/);
assert.match(info, /point\.lng\.toFixed\(6\)/);
assert.match(info, /!gps && areaName/);
assert.doesNotMatch(info, /fetch\(|dangerouslySetInnerHTML|iframe|contextmenu/);
assert.match(css, /\.position-info-popup a\.leaflet-popup-close-button \{[^}]*width: 44px;[^}]*height: 44px;/);
console.log('Pin location OK: single-tap Marker Popup, exact pin coordinates, official 3D, shared closing history, no invented address or background reverse lookup.');
