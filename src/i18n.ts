export type CopyKey = keyof typeof COPY['en'];

export function text(language: Language, key: CopyKey, values: Record<string, string | number> = {}) {
  return COPY[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}

export function vehicleLabel(language: Language, vehicle: VehicleType) {
  const labels: Record<Language, Record<VehicleType, string>> = {
    'zh-Hant': { privateCar: '私家車', motorCycle: '電單車', LGV: '輕型貨車', HGV: '重型貨車', coach: '旅遊巴' },
    en: { privateCar: 'Private car', motorCycle: 'Motorcycle', LGV: 'Light goods vehicle', HGV: 'Heavy goods vehicle', coach: 'Coach' },
  };
  return labels[language][vehicle];
}

export function vacancyLabel(language: Language, status: VacancyStatus) {
  if (language === 'zh-Hant') return status.label;
  if (status.kind === 'count') return `${status.count ?? 0} spaces`;
  return { available: 'Available', full: 'Full', closed: 'Closed', unknown: 'No data' }[status.kind];
}

export function updatedLabel(language: Language, value?: Date) {
  if (!value) return text(language, 'unavailable');
  const minutes = Math.max(0, Math.floor((Date.now() - value.getTime()) / 60_000));
  if (language === 'zh-Hant') return minutes < 1 ? '剛剛更新' : minutes < 60 ? `${minutes} 分鐘前更新` : `${Math.floor(minutes / 60)} 小時前更新`;
  return minutes < 1 ? 'Updated just now' : minutes < 60 ? `Updated ${minutes} min ago` : `Updated ${Math.floor(minutes / 60)} hr ago`;
}

export function heightLabel(language: Language, height?: number) {
  return height ? `${height.toFixed(height % 1 === 0 ? 0 : 1)} m` : text(language, 'unavailable');
}

export function facilityLabel(language: Language, facility: string) {
  const labels: Record<string, [string, string]> = {
    evCharger: ['充電設施', 'EV charging'], disabilities: ['無障礙設施', 'Accessible'], unloading: ['上落貨區', 'Loading bay'], washing: ['洗車服務', 'Car wash'], 'valet-parking': ['代客泊車', 'Valet parking'],
  };
  return labels[facility]?.[language === 'en' ? 1 : 0] ?? facility;
}

